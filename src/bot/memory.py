"""Agent memory export (docs/05-memory.md layer 2).

- ``memory/state.json``: current values only (no history), regenerated by the EOD job.
- ``session_context``: a condensed state + latest lessons, printed by the SessionStart
  hook so an agent starts with recall at a cost of a few hundred tokens.

No secrets or account numbers are ever written here.

CLI: ``python -m bot.memory context``.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from collections.abc import Mapping, Sequence
from datetime import datetime
from pathlib import Path
from typing import Any

from bot.journal import PositionRow

STRATEGY_VERSION = "trend-pullback-v1"
DEFAULT_MEMORY_DIR = Path("memory")


def build_state(
    as_of: datetime,
    equity: float,
    peak_equity: float,
    flags: Mapping[str, bool],
    positions: Sequence[PositionRow],
    prices: Mapping[str, float],
    last_runs: Mapping[str, str],
    mode: str = "paper",
) -> dict[str, Any]:
    drawdown = 0.0 if peak_equity <= 0 else max(0.0, 1 - equity / peak_equity)
    open_positions = []
    for p in positions:
        price = prices.get(p.symbol, p.entry_price)
        r = (price - p.entry_price) / (p.entry_price - p.initial_stop)
        open_positions.append(
            {
                "symbol": p.symbol,
                "shares": p.shares,
                "entry": round(p.entry_price, 2),
                "stop": round(p.stop, 2),
                "r_multiple": round(r, 2),
                "days_held": p.days_held,
            }
        )
    return {
        "as_of": as_of.isoformat(),
        "mode": mode,
        "equity": round(equity, 2),
        "peak_equity": round(peak_equity, 2),
        "drawdown_pct": round(drawdown * 100, 2),
        "flags": dict(flags),
        "open_positions": open_positions,
        "last_runs": dict(last_runs),
        "strategy_version": STRATEGY_VERSION,
    }


def write_state(path: Path, state: Mapping[str, Any]) -> None:
    """Atomic write: a reader never sees a half-written file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
    with os.fdopen(fd, "w") as fh:
        json.dump(state, fh, indent=1)
        fh.write("\n")
    os.replace(tmp, path)


def session_context(memory_dir: Path = DEFAULT_MEMORY_DIR, max_lessons: int = 10) -> str:
    state_path = memory_dir / "state.json"
    if not state_path.exists():
        lines = ["StockTradingBot: no state yet (state.json is written by the EOD job)."]
    else:
        s = json.loads(state_path.read_text())
        flags = ", ".join(f"{k}={'yes' if v else 'no'}" for k, v in s.get("flags", {}).items())
        symbols = ", ".join(p["symbol"] for p in s.get("open_positions", [])) or "none"
        lines = [
            f"StockTradingBot state as of {s.get('as_of')}: equity {s.get('equity', 0):.0f}, "
            f"drawdown {s.get('drawdown_pct', 0)}%, flags: {flags or 'none'}",
            f"Open positions: {symbols}",
        ]
    lessons_path = memory_dir / "lessons.md"
    if lessons_path.exists():
        bullets = [ln for ln in lessons_path.read_text().splitlines() if ln.startswith("- ")]
        if bullets:
            lines += ["Latest lessons:", *bullets[-max_lessons:]]
    lines.append("Memory protocol: memory/README.md. Hard rules: AGENTS.md.")
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args[:1] == ["context"]:
        print(session_context())
        return 0
    print("usage: python -m bot.memory context", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
